-- Backfill: add nullable FK columns, match existing free-text values by slug,
-- then tighten to NOT NULL once every row has a value.
ALTER TABLE agents ADD COLUMN region_id UUID;
ALTER TABLE agents ADD COLUMN district_id UUID;

UPDATE agents a
SET region_id = (
    SELECT r.id FROM regions r
    WHERE r.slug = lower(regexp_replace(trim(a.region), '\s+', '-', 'g'))
    LIMIT 1
);
UPDATE agents
SET region_id = (SELECT id FROM regions WHERE external_id = 'TZ01')
WHERE region_id IS NULL;

UPDATE agents a
SET district_id = (
    SELECT d.id FROM districts d
    WHERE d.region_id = a.region_id
      AND d.slug = lower(regexp_replace(trim(a.district), '\s+', '-', 'g'))
    LIMIT 1
);
UPDATE agents a
SET district_id = (SELECT d2.id FROM districts d2 WHERE d2.region_id = a.region_id ORDER BY d2.id LIMIT 1)
WHERE district_id IS NULL;

ALTER TABLE agents ALTER COLUMN region_id SET NOT NULL;
ALTER TABLE agents ALTER COLUMN district_id SET NOT NULL;

ALTER TABLE agents ADD CONSTRAINT fk_agents_region FOREIGN KEY (region_id) REFERENCES regions (id);
ALTER TABLE agents ADD CONSTRAINT fk_agents_district FOREIGN KEY (district_id) REFERENCES districts (id);

ALTER TABLE agents DROP COLUMN region;
ALTER TABLE agents DROP COLUMN district;
